const messages: Record<UiLocale, Messages> = { ru, kk, en }

export const localeOptions: Array<{ id: UiLocale; name: string }> = [
  { id: 'ru', name: 'Русский' },
  { id: 'kk', name: 'Қазақша' },
  { id: 'en', name: 'English' },
]

export function useAppI18n() {
  const ui = useUiPreferencesStore()
  const currentMessages = computed(() => messages[ui.locale])
  function t(key: string, fallback?: string): string {
    return currentMessages.value[key] ?? ru[key] ?? fallback ?? key
  }
  return { t, locale: computed(() => ui.locale), localeOptions }
}
