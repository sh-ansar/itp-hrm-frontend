export function usePublicSiteText() {
  const ui = useUiPreferencesStore()
  if (!savedLanguage.value) savedLanguage.value = loadLanguage(isLanguage(ui.locale) ? ui.locale : 'ru')
  const locale = computed<PublicLanguage>({
    get: () => savedLanguage.value || 'ru',
    set: (value) => {
      if (!isLanguage(value)) return
      savedLanguage.value = value
      try { window.localStorage.setItem('hrm-public-language', value) } catch { /* Optional persistence. */ }
      if (value === 'ru' || value === 'en' || value === 'ka') ui.setLocale(value)
    },
  })
  // API and approved legal records currently support RU/EN/GE only.
  // For the additional public languages, use official English documents; do not fabricate a legal translation.
  const serverLocale = computed<'ru' | 'en' | 'ka'>(() =>
    locale.value === 'ru' || locale.value === 'ka' ? locale.value : 'en')
  const tr = (key: SaasKey | string): string => {
    const language = locale.value
    const keyText = String(key)
    const page = siteText[language]?.[keyText]
    if (page) return page
    if (language === 'ru' || language === 'en' || language === 'ka') {
      return (saasCopy[language] as Record<string,string>)[keyText] || saasCopy.en[keyText as SaasKey] || keyText
    }
    return extraPublic[language][keyText] || saasCopy.en[keyText as SaasKey] || keyText
  }
  return { tr, locale, serverLocale, ui, setLocale: (value: PublicLanguage) => { locale.value = value } }
}
