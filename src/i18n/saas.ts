export type SaasKey = keyof typeof saasCopy.ru
export function useSaasText() {
  const ui = useUiPreferencesStore()
  const locale = computed<'ru' | 'en' | 'ka'>(() => ui.locale === 'ka' ? 'ka' : ui.locale === 'en' ? 'en' : 'ru')
  const tr = (key: SaasKey): string =>
    (saasCopy[locale.value] as Record<string, string>)[key] || saasCopy.ru[key]
  return { tr, locale, ui }
}
